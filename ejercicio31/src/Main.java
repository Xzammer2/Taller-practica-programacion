public class Main {

    public static void imprimirNaturales() {
        System.out.println("--- 10 PRIMEROS NÚMEROS NATURALES ---");
        for (int i = 1; i <= 10; i++) {
            System.out.print(i + " ");
        }
        System.out.println();
    }

    public static void main(String[] args) {
        imprimirNaturales();
    }
}